/* SERVISYO - run this BEFORE updating a database to v2.2 (EF migration AdminTargets).
   It only READS and changes nothing. Run it on LocalDB (and later on MonsterASP before deploying).

   Grid 1: how every ADMIN_ACTIONS row will look after the update (NEW_TYPE + the one filled NEW_..._ID column).
   Grid 2: rows the update cannot convert. If grid 2 is EMPTY, the update is safe to run.
           If it lists rows, the update stops without changing anything - send grid 2 to Claude. */

-- 1. Every row, before -> after
SELECT a.ACTION_ID,
       a.TARGET_TYPE AS OLD_TYPE,
       a.TARGET_ID   AS OLD_ID,
       CASE
           WHEN a.TARGET_TYPE = N'USER' AND c.CUSTOMER_ID IS NOT NULL AND p.PROVIDER_ID IS NULL THEN N'CUSTOMER'
           WHEN a.TARGET_TYPE = N'USER' AND p.PROVIDER_ID IS NOT NULL AND c.CUSTOMER_ID IS NULL THEN N'SERVICE_PROVIDER'
           WHEN a.TARGET_TYPE = N'SERVICE_PROVIDER' AND sp.PROVIDER_ID IS NOT NULL THEN N'SERVICE_PROVIDER'
           WHEN a.TARGET_TYPE = N'REVIEW' AND r.REVIEW_ID IS NOT NULL THEN N'REVIEW'
           WHEN a.TARGET_TYPE = N'CATEGORY' AND sc.CATEGORY_ID IS NOT NULL THEN N'CATEGORY'
       END AS NEW_TYPE,
       CASE WHEN a.TARGET_TYPE = N'USER' AND p.PROVIDER_ID IS NULL THEN c.CUSTOMER_ID END AS NEW_CUSTOMER_ID,
       CASE WHEN a.TARGET_TYPE = N'USER' AND c.CUSTOMER_ID IS NULL THEN p.PROVIDER_ID
            WHEN a.TARGET_TYPE = N'SERVICE_PROVIDER' THEN sp.PROVIDER_ID END AS NEW_PROVIDER_ID,
       r.REVIEW_ID   AS NEW_REVIEW_ID,
       sc.CATEGORY_ID AS NEW_CATEGORY_ID
FROM dbo.ADMIN_ACTIONS a
LEFT JOIN dbo.CUSTOMERS c           ON a.TARGET_TYPE = N'USER'             AND c.USER_ID = a.TARGET_ID
LEFT JOIN dbo.SERVICE_PROVIDERS p   ON a.TARGET_TYPE = N'USER'             AND p.USER_ID = a.TARGET_ID
LEFT JOIN dbo.SERVICE_PROVIDERS sp  ON a.TARGET_TYPE = N'SERVICE_PROVIDER' AND sp.PROVIDER_ID = a.TARGET_ID
LEFT JOIN dbo.REVIEWS r             ON a.TARGET_TYPE = N'REVIEW'           AND r.REVIEW_ID = a.TARGET_ID
LEFT JOIN dbo.SERVICE_CATEGORIES sc ON a.TARGET_TYPE = N'CATEGORY'         AND sc.CATEGORY_ID = a.TARGET_ID
ORDER BY a.ACTION_ID;

-- 2. Rows that cannot be converted (must be EMPTY)
SELECT x.ACTION_ID, x.OLD_TYPE, x.OLD_ID
FROM (
    SELECT a.ACTION_ID,
           a.TARGET_TYPE AS OLD_TYPE,
           a.TARGET_ID   AS OLD_ID,
           CASE
               WHEN a.TARGET_TYPE = N'USER' AND c.CUSTOMER_ID IS NOT NULL AND p.PROVIDER_ID IS NULL THEN N'CUSTOMER'
               WHEN a.TARGET_TYPE = N'USER' AND p.PROVIDER_ID IS NOT NULL AND c.CUSTOMER_ID IS NULL THEN N'SERVICE_PROVIDER'
               WHEN a.TARGET_TYPE = N'SERVICE_PROVIDER' AND sp.PROVIDER_ID IS NOT NULL THEN N'SERVICE_PROVIDER'
               WHEN a.TARGET_TYPE = N'REVIEW' AND r.REVIEW_ID IS NOT NULL THEN N'REVIEW'
               WHEN a.TARGET_TYPE = N'CATEGORY' AND sc.CATEGORY_ID IS NOT NULL THEN N'CATEGORY'
           END AS NEW_TYPE,
           CASE WHEN a.TARGET_TYPE = N'USER' AND p.PROVIDER_ID IS NULL THEN c.CUSTOMER_ID END AS NEW_CUSTOMER_ID,
           CASE WHEN a.TARGET_TYPE = N'USER' AND c.CUSTOMER_ID IS NULL THEN p.PROVIDER_ID
                WHEN a.TARGET_TYPE = N'SERVICE_PROVIDER' THEN sp.PROVIDER_ID END AS NEW_PROVIDER_ID,
           r.REVIEW_ID   AS NEW_REVIEW_ID,
           sc.CATEGORY_ID AS NEW_CATEGORY_ID
    FROM dbo.ADMIN_ACTIONS a
    LEFT JOIN dbo.CUSTOMERS c           ON a.TARGET_TYPE = N'USER'             AND c.USER_ID = a.TARGET_ID
    LEFT JOIN dbo.SERVICE_PROVIDERS p   ON a.TARGET_TYPE = N'USER'             AND p.USER_ID = a.TARGET_ID
    LEFT JOIN dbo.SERVICE_PROVIDERS sp  ON a.TARGET_TYPE = N'SERVICE_PROVIDER' AND sp.PROVIDER_ID = a.TARGET_ID
    LEFT JOIN dbo.REVIEWS r             ON a.TARGET_TYPE = N'REVIEW'           AND r.REVIEW_ID = a.TARGET_ID
    LEFT JOIN dbo.SERVICE_CATEGORIES sc ON a.TARGET_TYPE = N'CATEGORY'         AND sc.CATEGORY_ID = a.TARGET_ID
) x
WHERE x.NEW_TYPE IS NULL
ORDER BY x.ACTION_ID;
